// Bot playtester: plays every level many times and reports pass and 3-star rates.
// The bot (tools/botlib.mjs) is greedy, with no lookahead, and brings one of these buddies:
//   starter = Mochi at level 1 (Fetch x1)            mid     = a level-3 rare at Bond 5 (Dig x3, +12%)
//   maxEpic = a maxed epic (Cannonball x5)           maxBond = a maxed epic at Bond 10 (Cannonball x5, +27%)
// Usage: node tools/bot.mjs [games per level] [world id] [first level] [last level]
//        node tools/bot.mjs tune [games per level] [world id ...]  -> updates www/js/tuning.js
// Tuning sets each level's stars from bot score percentiles. Worlds 1 and 2 are set so basic pups
// and patience clear them; from World 3 on, 3 stars assume a maxed, fully bonded pup, and from
// World 4 on, even 1 star assumes a leveled rare.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { play } from './botlib.mjs';
const require = createRequire(import.meta.url);
const Levels = require('../www/js/levels.js');
const Tuning = require('../www/js/tuning.js');

const TUNE = process.argv[2] === 'tune';
const N = Number(process.argv[TUNE ? 3 : 2] || 30);
const TUNE_WORLDS = TUNE ? (process.argv.slice(4).length ? process.argv.slice(4) : Levels.WORLDS.map((w) => w.id)) : [];
const WORLD = TUNE ? null : process.argv[3] || 'w1';
const FROM = Number(process.argv[4] || 1), TO = Number(process.argv[5] || 40);

// Share of bot runs that should FAIL each star, and which buddy each star is measured against.
// Humans plan ahead and beat this greedy bot, so real pass rates will run higher than the bot's.
function quantiles(level) {
  const n = level.n;
  const band = (a, b, c, d) => (n <= 10 ? a : n <= 20 ? b : n <= 30 ? c : d);
  const nudge = (one) => (n % 5 === 0 ? one + 0.1 : n % 5 === 1 && n > 1 ? one - 0.1 : one); // dig levels harder, the next a breather
  switch (level.world) {
    case 'w1': // Living Room: 3 stars against a starter on 1-20, a maxed epic on 21-40
      return { one: nudge(band(0.15, 0.3, 0.45, 0.55)), oneFrom: 'starter', three: n < 40 ? band(0.45, 0.8, 0.72, 0.86) : 0.93, threeFrom: n <= 20 ? 'starter' : 'maxEpic' };
    case 'w2': // Dog Park opens mid-Living Room, so it starts about where Living Room 20 sits
      return { one: nudge(band(0.3, 0.4, 0.5, 0.6)), oneFrom: 'starter', three: n < 40 ? band(0.75, 0.65, 0.8, 0.9) : 0.95, threeFrom: n <= 10 ? 'starter' : 'maxEpic' };
    case 'w3': // Beach: 1 star still a starter's; 3 stars need a maxed, bonded pup
      return { one: nudge(band(0.35, 0.45, 0.55, 0.62)), oneFrom: 'starter', three: n < 40 ? band(0.7, 0.8, 0.88, 0.92) : 0.96, threeFrom: 'maxBond' };
    case 'w4': // Snowy Hill: 1 star assumes a leveled rare
      return { one: nudge(band(0.35, 0.45, 0.55, 0.62)), oneFrom: 'mid', three: n < 40 ? band(0.75, 0.85, 0.9, 0.93) : 0.97, threeFrom: 'maxBond' };
    default: // Autumn Backyard
      return { one: nudge(band(0.4, 0.5, 0.6, 0.66)), oneFrom: 'mid', three: n < 40 ? band(0.8, 0.88, 0.92, 0.95) : 0.98, threeFrom: 'maxBond' };
  }
}
const at = (sorted, q) => sorted[Math.min(sorted.length - 1, Math.max(0, Math.floor(q * sorted.length)))];
const r50 = (x) => Math.max(50, Math.round(x / 50) * 50);
const runs = (level, kind) => Array.from({ length: N }, (_, k) => play(level, kind, 1000 + k * 7919).score).sort((a, b) => a - b);
const rate = (arr, t) => Math.round((100 * arr.filter((x) => x >= t).length) / arr.length);

if (TUNE) {
  const out = Object.assign({}, Tuning);
  for (const world of Levels.WORLDS.filter((w) => TUNE_WORLDS.includes(w.id))) {
    console.log(`== ${world.name}`);
    for (const level of world.levels) {
      const q = quantiles(level);
      const scores = {};
      for (const kind of new Set([q.oneFrom, q.threeFrom, 'starter'])) scores[kind] = runs(level, kind);
      const t1 = r50(at(scores[q.oneFrom], q.one));
      const t3 = Math.max(r50(at(scores[q.threeFrom], q.three)), t1 + 100);
      const t2 = Math.min(Math.max(r50(Math.sqrt(t1 * t3)), t1 + 50), t3 - 50);
      out[level.id] = [t1, t2, t3];
      const s = scores.starter, m = scores[q.threeFrom];
      console.log(`${String(level.n).padStart(2)} ${level.name.padEnd(22)} ${String(t1).padStart(5)} / ${String(t2).padStart(5)} / ${String(t3).padStart(5)}  starter pass ${String(rate(s, t1)).padStart(3)}% 3★ ${String(rate(s, t3)).padStart(2)}%  ${q.threeFrom} pass ${String(rate(m, t1)).padStart(3)}% 3★ ${String(rate(m, t3)).padStart(3)}%${q.oneFrom !== 'starter' && q.oneFrom !== q.threeFrom ? `  ${q.oneFrom} pass ${rate(scores[q.oneFrom], t1)}%` : ''}`);
    }
  }
  const order = Levels.LEVELS.map((l) => l.id).filter((id) => out[id]);
  const body = order.map((id) => `    '${id}': [${out[id].join(', ')}],`).join('\n');
  writeFileSync(new URL('../www/js/tuning.js', import.meta.url), `// Generated by tools/bot.mjs tune (${N} bot runs per level per buddy). Do not edit by hand:
// re-run the tuner after changing a level. [1 star, 2 stars, 3 stars]
(function (root) {
  'use strict';
  const LevelTuning = {
${body}
  };
  root.PB = root.PB || {};
  root.PB.LevelTuning = LevelTuning;
  if (typeof module !== 'undefined' && module.exports) module.exports = LevelTuning;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`);
  console.log('wrote www/js/tuning.js');
  process.exit(0);
}

const reportWorld = Levels.WORLDS.find((w) => w.id === WORLD);
if (!reportWorld) {
  console.error(`Unknown world "${WORLD}". Worlds: ${Levels.WORLDS.map((w) => w.id).join(', ')}`);
  process.exit(1);
}
for (const level of reportWorld.levels.slice(FROM - 1, TO)) {
  const [t1, , t3] = Levels.starsFor(level);
  const cols = ['starter', 'mid', 'maxBond'].map((kind) => {
    const s = runs(level, kind);
    return `${kind} ${String(rate(s, t1)).padStart(3)}% pass ${String(rate(s, t3)).padStart(3)}% 3★ med ${String(s[Math.floor(N / 2)]).padStart(6)}`;
  });
  console.log(`${String(level.n).padStart(2)} ${level.name.padEnd(22)} 1★ ${String(t1).padStart(5)} 3★ ${String(t3).padStart(6)} | ${cols.join(' | ')}`);
}
